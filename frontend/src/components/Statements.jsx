import { useEffect, useState } from 'react';
import { api, apiUrl } from '../lib/api';
import { formatDateTime } from '../lib/format';
import { useAuth } from '../context/AuthContext';

function today()      { return new Date().toISOString().slice(0, 10); }
function monthsAgo(n) { const d = new Date(); d.setMonth(d.getMonth() - n); return d.toISOString().slice(0, 10); }

export default function Statements({ accounts }) {
  const { token } = useAuth();
  const [items, setItems] = useState([]);
  const [accountId, setAccountId] = useState(accounts[0]?.id || '');
  const [startDate, setStartDate] = useState(monthsAgo(1));
  const [endDate, setEndDate]     = useState(today());
  const [error, setError] = useState('');

  const load = () => api('/api/statements', { token }).then(setItems).catch(console.error);
  useEffect(() => { load(); }, [token]);
  useEffect(() => {
    const iv = setInterval(load, 3000);   // poll for status changes
    return () => clearInterval(iv);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [token]);

  async function request(e) {
    e.preventDefault();
    setError('');
    try {
      await api('/api/statements', {
        method: 'POST', token,
        body: { accountId: Number(accountId), startDate, endDate },
      });
      load();
    } catch (e) { setError(e.message); }
  }

  return (
    <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
      <section className="lg:col-span-1">
        <div className="card p-6">
          <h2 className="text-lg font-semibold mb-4">Request a statement</h2>
          <form onSubmit={request} className="space-y-3">
            <div>
              <label className="label">Account</label>
              <select className="input" value={accountId}
                      onChange={(e) => setAccountId(e.target.value)}>
                {accounts.map((a) => (
                  <option key={a.id} value={a.id}>
                    {a.account_number} — {a.currency}
                  </option>
                ))}
              </select>
            </div>
            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="label">Start</label>
                <input type="date" className="input" value={startDate}
                       onChange={(e) => setStartDate(e.target.value)} />
              </div>
              <div>
                <label className="label">End</label>
                <input type="date" className="input" value={endDate}
                       onChange={(e) => setEndDate(e.target.value)} />
              </div>
            </div>
            {error && <div className="text-sm text-debit">{error}</div>}
            <button className="btn-primary w-full">Request PDF</button>
            <p className="text-xs text-slate-500">
              Generated by a background worker. Usually ready in a few seconds.
            </p>
          </form>
        </div>
      </section>

      <section className="lg:col-span-2">
        <div className="card">
          <div className="px-6 py-4 border-b border-border">
            <h2 className="text-lg font-semibold">Requested statements</h2>
          </div>
          {items.length === 0 ? (
            <div className="p-8 text-center text-sm text-slate-500">
              No statements requested yet.
            </div>
          ) : (
            <ul className="divide-y divide-border">
              {items.map((s) => (
                <li key={s.id} className="px-6 py-4 flex items-center justify-between">
                  <div>
                    <div className="text-sm font-medium text-ink font-mono">
                      {s.account_number}
                    </div>
                    <div className="text-xs text-slate-500">
                      {s.start_date.slice(0,10)} → {s.end_date.slice(0,10)} ·
                      {' '}Requested {formatDateTime(s.requested_at)}
                    </div>
                  </div>
                  <div className="flex items-center gap-3">
                    <span className={`text-xs uppercase px-2 py-0.5 rounded ${
                      s.status === 'ready' ? 'bg-accentSoft text-accent' :
                      s.status === 'failed' ? 'bg-red-50 text-debit' :
                      'bg-slate-100 text-slate-600'
                    }`}>{s.status}</span>
                    {s.status === 'ready' && (
                      <a
                        href={apiUrl(`/api/statements/${s.id}/download`)}
                        // Fetch with token header, then trigger download
                        onClick={async (e) => {
                          e.preventDefault();
                          const res = await fetch(apiUrl(`/api/statements/${s.id}/download`), {
                            headers: { Authorization: `Bearer ${token}` },
                          });
                          const blob = await res.blob();
                          const url = URL.createObjectURL(blob);
                          const a = document.createElement('a');
                          a.href = url;
                          a.download = `statement-${s.id}.pdf`;
                          a.click();
                          URL.revokeObjectURL(url);
                        }}
                        className="btn-primary text-xs"
                      >
                        Download
                      </a>
                    )}
                  </div>
                </li>
              ))}
            </ul>
          )}
        </div>
      </section>
    </div>
  );
}
